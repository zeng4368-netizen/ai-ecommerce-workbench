"""Helpers to convert browser cookie exports into the Netscape format yt-dlp needs.

Newer Edge/Chrome builds encrypt cookies with App-Bound Encryption (ABE), which
yt-dlp cannot decrypt with plain DPAPI (yt-dlp issue #10927), so reading Edge
cookies directly (``--cookies-from-browser edge``) fails. A reliable workaround
is to export cookies from the browser itself (e.g. the Cookie-Editor extension,
which the browser lets decrypt its own cookies) and feed the file to yt-dlp via
``--cookies``.
"""

from __future__ import annotations

import json
from pathlib import Path


def _to_expiry(expires: float | None) -> int:
    """Return a session-safe expiry: 0 for session cookies, else epoch seconds."""
    if not expires:
        return 0
    value = int(expires)
    return value if value > 0 else 0


def cookies_json_to_netscape(cookie_json: str, output: Path) -> int:
    """Convert a Cookie-Editor style cookie list (JSON) to Netscape cookies.txt.

    Accepts either a JSON array of cookie objects or an object with a ``cookies``
    key. Each cookie object supports the fields emitted by Cookie-Editor:
    ``domain``, ``expirationDate``, ``hostOnly``, ``httpOnly``, ``name``,
    ``path``, ``sameSite``, ``secure``, ``session``, ``storeId``, ``value``.
    """
    data = json.loads(cookie_json)
    if isinstance(data, dict):
        data = data.get("cookies", data)
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by ecom_ops.video_mixer.cookie_tools (browser export)",
        "",
    ]
    written = 0
    for cookie in data:
        domain = str(cookie.get("domain", ""))
        name = str(cookie.get("name", ""))
        value = str(cookie.get("value", ""))
        path = str(cookie.get("path", "/"))
        if not domain or not name or "\t" in value or "\n" in value or "\r" in value:
            continue
        secure = "TRUE" if cookie.get("secure") else "FALSE"
        include_subdomains = "FALSE" if cookie.get("hostOnly") else "TRUE"
        if not domain.startswith("."):
            # Netscape format uses a leading dot + TRUE for subdomain cookies;
            # host-only cookies keep the bare domain with FALSE.
            include_subdomains = "FALSE"
        expires = _to_expiry(cookie.get("expirationDate"))
        if cookie.get("session"):
            expires = 0
        lines.append(f"{domain}\t{include_subdomains}\t{path}\t{secure}\t{expires}\t{name}\t{value}")
        written += 1
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return written


def convert_cookie_file(source: Path, output: Path | None = None) -> int:
    """Read a JSON cookie export file and write the Netscape version."""
    output = output or source.with_suffix(".txt")
    return cookies_json_to_netscape(source.read_text(encoding="utf-8-sig"), output)
